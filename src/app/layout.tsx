/**
 * Estado respecto al último commit: MODIFICADO para importar AuthSessionProvider
 * y envolver las páginas, de modo que puedan consultar la sesión con useSession.
 * Las fuentes, los metadatos y el idioma actuales proceden de la plantilla inicial.
 * En esta revisión se añaden comentarios para estudiar la implementación.
 * Propósito: definir el documento HTML y la estructura compartida por las páginas.
 * Extensión .tsx: combina tipos TypeScript con JSX, como <html> y <body>.
 * .ts no admite ese JSX. Este archivo sigue siendo un componente de servidor:
 * usar .tsx no lo convierte en cliente, y el proveedor encapsula la parte cliente.
 * Flujo: Next.js entrega la página como children y el proveedor comparte su sesión
 * con los componentes cliente descendientes, sin convertir esos children en módulos cliente.
 */

// Importa solo el tipo de metadatos para comprobar su estructura; no añade una importación al JavaScript compilado.
import type { Metadata } from "next";
// Importa las dos fuentes gestionadas por Next.js para integrarlas mediante variables CSS.
import { Geist, Geist_Mono } from "next/font/google";
// Carga los estilos globales una vez desde el layout raíz para que estén disponibles en las páginas.
import "./globals.css";
// Importa el envoltorio cliente que comparte la sesión sin añadir use client al layout.
import { AuthSessionProvider } from "./session-provider";

// Configura la fuente proporcional de la plantilla con next/font para que Next.js gestione sus archivos y estilos.
const geistSans = Geist({
  // Expone la familia como variable CSS para que los estilos puedan utilizarla.
  variable: "--font-geist-sans",
  // Selecciona el subconjunto latino que se precarga, evitando precargar otros subconjuntos innecesarios para esta interfaz.
  subsets: ["latin"],
}); // Cierra la configuración de Geist y guarda el resultado generado por next/font.

// Configura la variante monoespaciada de la plantilla, útil para estilos de texto con caracteres del mismo ancho.
const geistMono = Geist_Mono({
  // Usa una variable distinta para poder elegir esta fuente sin sobrescribir la proporcional.
  variable: "--font-geist-mono",
  // Precarga también el subconjunto latino para esta familia.
  subsets: ["latin"],
}); // Cierra la configuración de Geist Mono y conserva sus clases y variables generadas.

// Exporta metadatos tipados para que Next.js construya el head del documento desde el servidor.
export const metadata: Metadata = {
  // Conserva el título de la plantilla, que Next.js utiliza como título del documento y de la pestaña.
  title: "Create Next App",
  // Conserva la descripción inicial que Next.js incluye en la etiqueta meta description.
  description: "Generated by create next app",
}; // Termina los metadatos; esta exportación es una razón para mantener el layout como componente de servidor.

// Exporta el layout raíz; children contiene la página y LayoutProps es un tipo global que genera Next.js para la ruta /.
export default function RootLayout({ children }: LayoutProps<"/">) {
  // Devuelve la estructura JSX del documento; el layout raíz debe incluir html y body según la convención de Next.js.
  return (
    // Abre el elemento raíz del documento para definir su idioma y clases comunes.
    <html
      // Mantiene el idioma inglés de la plantilla; lang informa a lectores de pantalla y otras herramientas sobre el idioma declarado.
      lang="en"
      // Combina las clases que exponen las fuentes con altura completa y suavizado de texto de Tailwind.
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
      // Finaliza los atributos y abre el contenido del elemento html.
    >
      {/* Abre el cuerpo; min-h-full establece una altura mínima y flex-col organiza sus elementos en una columna. */}
      <body className="min-h-full flex flex-col">
        {/* Envuelve la página con el contexto de sesión; los componentes cliente descendientes pueden usar useSession. */}
        <AuthSessionProvider>{children}</AuthSessionProvider>
        {/* Cierra el cuerpo después del contenido de la página y su proveedor. */}
      </body>
      {/* Cierra el elemento raíz requerido por Next.js. */}
    </html>
  ); // Termina la expresión JSX que devuelve la estructura compartida.
} // Cierra RootLayout; Next.js lo utiliza para envolver las páginas de la aplicación.
